#!/usr/bin/env bash
# Topic 15: export what potato's web/ and indexer/ need about the LayerZero lab into
# ../../potato-chain/deployments/layerzero.json (chains, endpoints, start blocks, bridge legs).
# Source of truth stays here (config/topology.json + deployments/*.json); re-run after any redeploy.
# usage: ./export-to-potato.sh [out-file]
set -euo pipefail
export PATH="$HOME/.foundry/bin:$PATH"
cd "$(dirname "$0")"
T=config/topology.json
OUT="${1:-../../potato-chain/deployments/layerzero.json}"

# Block that deployed endpoint $1 on $2 = block of its first log (the constructor emits OwnershipTransferred).
# Logs, not eth_getCode at old blocks: anvil restored from --state has the blocks but no historical state.
# The indexer must start there, never at block 0 (getLogs bug on unpatched cosmos/evm).
# Scanned in 5,000-block windows: cosmos/evm rejects a single getLogs over a longer range.
deploy_block() {
  local from=1 tip first
  tip=$(cast block-number --rpc-url "$2")
  while [ "$from" -le "$tip" ]; do
    first=$(cast logs --from-block "$from" --to-block $((from + 4999)) --address "$1" --rpc-url "$2" --json | jq -r '.[0].blockNumber // empty')
    [ -n "$first" ] && { cast to-dec "$first"; return; }
    from=$((from + 5000))
  done
  echo "no logs from $1 on $2" >&2; exit 1
}

chains='{}'
for c in $(jq -r '.chains | keys[]' "$T"); do
  id=$(jq -r ".chains.$c.chainId" "$T"); D="deployments/$id.json"; ep=$(jq -r .EndpointV2 "$D")
  start=$(deploy_block "$ep" "$(jq -r ".chains.$c.rpc" "$T")")
  chains=$(jq --arg c "$c" --argjson start "$start" --slurpfile d "$D" --slurpfile t "$T" \
    '.[$c] = ($t[0].chains[$c] | {chainId, eid, rpc}) + {endpoint: $d[0].EndpointV2, startBlock: $start}' <<<"$chains")
  echo "$c: endpoint $ep from block $start" >&2
done

assets=$(jq -n --slurpfile t "$T" --argjson chains "$chains" '
  $t[0].assets | with_entries(.value |= {decimals, sharedDecimals, home,
    legs: (.legs | with_entries(.value = {kind: .value.kind, address: null}))})')
for a in $(jq -r '.assets | keys[]' "$T"); do
  for c in $(jq -r '.chains | keys[]' "$T"); do
    D="deployments/$(jq -r ".chains.$c.chainId" "$T").json"
    assets=$(jq --arg a "$a" --arg c "$c" --arg addr "$(jq -r ".$a" "$D")" '.[$a].legs[$c].address = $addr' <<<"$assets")
  done
done
# the home token behind an ERC-20 adapter (USDC): the leg locks it, the UI must approve it
assets=$(jq --arg t "$(jq -r '.IssuerUSDC // empty' "deployments/$(jq -r '.chains[.assets.USDC.home].chainId' "$T").json")" \
  'if $t != "" then .USDC.homeToken = $t else . end' <<<"$assets")

jq -n --argjson chains "$chains" --argjson assets "$assets" \
  '{"$comment": "Generated by stable-coin-L0/lz-potato/export-to-potato.sh. Do not edit by hand.", chains: $chains, assets: $assets}' > "$OUT"
echo "wrote $OUT" >&2
